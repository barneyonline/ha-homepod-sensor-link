"""Generate a local, portable wiki from the canonical Markdown sources."""

import argparse
from html import escape
from pathlib import Path
import re
from urllib.parse import unquote, urlsplit

ROOT = Path(__file__).resolve().parents[1]
WIKI_URL = "https://github.com/barneyonline/ha-homepod-sensor-link/wiki"
PAGES = {
    "Home": "docs/DOCUMENTATION.md",
    "Getting-Started": "docs/SETUP.md",
    "Credential-Extraction": "docs/EXTRACTION.md",
    "Using-the-Integration": "docs/USAGE.md",
    "Automation-Examples": "docs/AUTOMATIONS.md",
    "Troubleshooting-and-Support": "docs/TROUBLESHOOTING.md",
    "Known-Limitations": "docs/LIMITATIONS.md",
    "Development-Environment": "docs/DEVELOPMENT.md",
    "Architecture": "docs/ARCHITECTURE.md",
    "Quality-and-Readiness": "docs/QUALITY.md",
    "Quality-Research": "docs/QUALITY_RESEARCH.md",
    "Dependencies": "docs/DEPENDENCIES.md",
    "Security": "SECURITY.md",
    "Validation": "docs/VALIDATION.md",
    "Research": "docs/RESEARCH.md",
    "UI-Research": "docs/UI_RESEARCH.md",
    "Completion-Boundaries": "docs/COMPLETION.md",
    "Roadmap": "docs/ROADMAP.md",
    "Repository-Standards": "docs/REPOSITORY_STANDARDS.md",
    "Contributing": "CONTRIBUTING.md",
    "Release-Notes": "CHANGELOG.md",
}
LINK = re.compile(r"(?P<start>!?\[[^\]]*\]\()(?P<target>[^)]+)(?P<end>\))")
HEADER = "<!-- Generated by scripts/build_wiki.py; edit its source page. -->\n\n"
BANNER_DIR = Path("docs/images/wiki")
WIKI_IMAGES_URL = "https://raw.githubusercontent.com/wiki/barneyonline/ha-homepod-sensor-link/images"


def banners(root):
    """Read a complete, regular-file banner set before writing any output."""
    directory = root / BANNER_DIR
    if not directory.exists():
        return {}
    result = {}
    for page in PAGES:
        for theme in ("dark", "light"):
            path = directory / f"{page}-{theme}.jpg"
            if any(p.is_symlink() for p in (path, *path.parents) if p == root or root in p.parents):
                raise ValueError("Banner symlink refused")
            if not path.is_file():
                raise ValueError(f"Missing wiki banner: {path.name}")
            result[path.name] = path.read_bytes()
    return result


def banner_header(page, *, github):
    base = WIKI_IMAGES_URL if github else "../docs/images/wiki"
    alt = escape(f"HomePod Sensor Link — {page.replace('-', ' ')}", quote=True)
    return (
        "<picture>\n"
        f'  <source media="(prefers-color-scheme: dark)" srcset="{base}/{page}-dark.jpg">\n'
        f'  <source media="(prefers-color-scheme: light)" srcset="{base}/{page}-light.jpg">\n'
        f'  <img alt="{alt}" src="{base}/{page}-light.jpg" width="1800" height="600">\n'
        "</picture>\n\n"
    )


def pages(root=ROOT, *, github=False):
    assets = banners(root)
    mapped = {(root / source).resolve(): page for page, source in PAGES.items()}
    mapped.update({(root / "wiki" / (page + ".md")).resolve(): page for page in PAGES})
    output = {}
    for page, source in PAGES.items():
        location = root / source

        def rewrite(match):
            target = match["target"]
            parsed = urlsplit(target)
            if not parsed.scheme and parsed.path:
                linked = (location.parent / unquote(parsed.path)).resolve()
                if linked in mapped:
                    target = WIKI_URL + "/" + mapped[linked] if github else mapped[linked] + ".md"
                    if parsed.fragment:
                        target += "#" + parsed.fragment
                else:
                    raise ValueError(f"Unmapped wiki link in {source}")
            return match["start"] + target + match["end"]

        banner = banner_header(page, github=github) if assets else ""
        output[page + ".md"] = HEADER + banner + LINK.sub(rewrite, location.read_text())
    sidebar = []
    for page in PAGES:
        target = WIKI_URL + "/" + page if github else page + ".md"
        sidebar.append(f"- [{page.replace('-', ' ')}]({target})")
    output["_Sidebar.md"] = HEADER + "# Navigation\n\n" + "\n".join(sidebar) + "\n"
    return output


def build(root=ROOT, *, check=False, github=False, output=None):
    if github and output is None:
        raise ValueError("GitHub export requires a separate output directory")
    directory = root / "wiki" if output is None else Path(output).resolve()
    if output is not None and (directory == root.resolve() or root.resolve() in directory.parents):
        raise ValueError("Keep exports outside the source tree")
    generated = pages(root, github=github)
    assets = banners(root) if github else {}
    existing = {p.name for p in directory.glob("*.md")}
    if existing - generated.keys():
        raise ValueError("Unexpected wiki pages; reconcile explicitly rather than deleting work")
    if check:
        stale = [
            name
            for name, value in generated.items()
            if not (directory / name).is_file() or (directory / name).read_text() != value
        ]
        stale.extend(
            name
            for name, content in assets.items()
            if not (directory / "images" / name).is_file() or (directory / "images" / name).read_bytes() != content
        )
        if stale:
            raise ValueError("Wiki is stale; run python3 scripts/build_wiki.py")
    else:
        directory.mkdir(exist_ok=True)
        for name, value in generated.items():
            (directory / name).write_text(value)
        if assets:
            images = directory / "images"
            images.mkdir(exist_ok=True)
            for name, content in assets.items():
                (images / name).write_bytes(content)
    label = "GitHub wiki export" if github else "Local wiki"
    print(f"{label} {'checked' if check else 'generated'}: {len(generated)} pages; no remote access.")


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--github", action="store_true", help="Use published GitHub Wiki page links")
    parser.add_argument("--output", type=Path, help="Separate export directory outside the source tree")
    args = parser.parse_args()
    build(check=args.check, github=args.github, output=args.output)
